"""Official manual library.

Holds the curated catalogue of manufacturer-published PDF manuals for Korg,
Yamaha and Roland arrangers, and can fetch them on demand.

Nothing is re-hosted here: every entry points at the official manufacturer URL
that was resolved from their own support portal and verified reachable.  When a
model is identified, this module is what lets the analyzer say *which document
explains this* instead of leaving the operator to search for it.

The catalogue lives in ``data/manuals.json`` and is generated by the scripts in
``tools/``; see ``README.md``.
"""

from __future__ import annotations

import json
import re
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Callable, Iterable

CATALOG_PATH = Path(__file__).resolve().parent / "data" / "manuals.json"

USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) KorgBinaryAnalyzer"
CHUNK = 256 * 1024

#: Document types that actually describe the on-disk format or its contents.
#: The authoritative flag is the per-entry ``depth`` field written by the
#: catalogue builder, which knows that a 1650-page Korg User Manual is
#: reference-grade while a Yamaha Owner's Manual is an introduction.  This set
#: remains as a fallback for older catalogues.
DEEP_REFERENCE = {
    "Reference Manual", "Advanced Edit / Reference", "Data List", "Parameters Guide",
    "MIDI Implementation", "Pre-installed Expansion Contents List", "User Manual",
    "Owner's Manual", "Style / Tone List", "Waveform / Patch List",
}


def load_catalog() -> dict[str, Any]:
    try:
        payload = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"schema": "korg-analyzer-manuals/1", "products": {}}
    if not isinstance(payload.get("products"), dict):
        payload["products"] = {}
    return payload


def products(catalog: dict[str, Any] | None = None) -> dict[str, Any]:
    return (catalog or load_catalog()).get("products", {})


def brands(catalog: dict[str, Any] | None = None) -> list[str]:
    return sorted({item["brand"] for item in products(catalog).values()})


def families(brand: str | None = None, catalog: dict[str, Any] | None = None) -> dict[str, list[str]]:
    """Group model names by product family (Pa3X, Pa3X Le and Pa3X MUSIKANT are one family)."""
    grouped: dict[str, list[str]] = {}
    for name, item in products(catalog).items():
        if brand and item["brand"].casefold() != brand.casefold():
            continue
        grouped.setdefault(item.get("family") or name, []).append(name)
    return {key: sorted(value) for key, value in sorted(grouped.items())}


def search(term: str, catalog: dict[str, Any] | None = None) -> list[tuple[str, dict[str, Any]]]:
    lowered = term.casefold().strip()
    if not lowered:
        return sorted(products(catalog).items())
    hits = []
    for name, item in products(catalog).items():
        haystack = " ".join([
            name, item.get("brand", ""), item.get("family", ""),
            item.get("generation", ""), item.get("container_era", ""),
            " ".join(doc.get("doc", "") for doc in item.get("docs", [])),
        ]).casefold()
        if lowered in haystack:
            hits.append((name, item))
    return sorted(hits)


def parse_size(value: str | None) -> int:
    """Turn ``"78.4MB"`` into bytes; 0 when unknown."""
    if not value:
        return 0
    match = re.match(r"\s*([\d.,]+)\s*([KMG])B\s*", value, re.I)
    if not match:
        return 0
    number = float(match.group(1).replace(",", ""))
    scale = {"K": 1024, "M": 1024 ** 2, "G": 1024 ** 3}[match.group(2).upper()]
    return int(number * scale)


def human_size(value: int) -> str:
    if not value:
        return "-"
    if value < 1024:
        return f"{value} B"
    if value < 1024 ** 2:
        return f"{value / 1024:.1f} KB"
    if value < 1024 ** 3:
        return f"{value / 1024 ** 2:.1f} MB"
    return f"{value / 1024 ** 3:.2f} GB"


def catalogue_size(catalog: dict[str, Any] | None = None) -> int:
    return sum(
        parse_size(doc.get("size"))
        for item in products(catalog).values()
        for doc in item.get("docs", [])
    )


def deep_reference_docs(product: dict[str, Any]) -> list[dict[str, Any]]:
    """Documents that explain the format and its contents, not just how to play."""
    docs = product.get("docs", [])
    if any("depth" in doc for doc in docs):
        return [doc for doc in docs if doc.get("depth") == "reference"]
    return [doc for doc in docs if doc.get("doc") in DEEP_REFERENCE]


def manuals_for_model(model: str, catalog: dict[str, Any] | None = None) -> list[tuple[str, dict[str, Any]]]:
    """Find catalogue entries whose name matches a model string seen in a file."""
    normalized = re.sub(r"[^a-z0-9]", "", model.casefold())
    if not normalized:
        return []
    hits: list[tuple[str, dict[str, Any]]] = []
    for name, item in products(catalog).items():
        candidate = re.sub(r"[^a-z0-9]", "", name.casefold())
        if candidate and (candidate in normalized or normalized in candidate):
            hits.append((name, item))
    # Longest match first so "Pa3X Le" wins over "Pa3X" for a Pa3X Le file.
    hits.sort(key=lambda pair: -len(re.sub(r"[^a-z0-9]", "", pair[0].casefold())))
    return hits


def download(
    url: str,
    target: Path,
    progress: Callable[[int, int], None] | None = None,
) -> dict[str, Any]:
    """Fetch one PDF.  Returns ``{"status", "path", "size"}``; never raises for I/O."""
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() and target.stat().st_size > 0:
        return {"status": "ALREADY_PRESENT", "path": str(target), "size": target.stat().st_size}
    partial = target.with_suffix(target.suffix + ".part")
    try:
        request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
        with urllib.request.urlopen(request, timeout=120) as response:
            declared = int(response.headers.get("Content-Length") or 0)
            written = 0
            with partial.open("wb") as handle:
                while chunk := response.read(CHUNK):
                    handle.write(chunk)
                    written += len(chunk)
                    if progress:
                        progress(written, declared)
        if declared and written != declared:
            partial.unlink(missing_ok=True)
            return {"status": "SIZE_MISMATCH", "path": str(target), "size": written, "expected": declared}
        partial.replace(target)
        return {"status": "DOWNLOADED", "path": str(target), "size": written}
    except (urllib.error.URLError, OSError, ValueError) as error:
        partial.unlink(missing_ok=True)
        return {"status": "FAILED", "path": str(target), "error": f"{type(error).__name__}: {error}"}


def plan_download(
    catalog: dict[str, Any] | None = None,
    brand: str | None = None,
    model: str | None = None,
    deep_only: bool = False,
) -> list[dict[str, Any]]:
    """Build the list of downloads that would run, without touching the network."""
    catalog = catalog or load_catalog()
    plan: list[dict[str, Any]] = []
    for name, item in products(catalog).items():
        if brand and item["brand"].casefold() != brand.casefold():
            continue
        if model and model.casefold() not in name.casefold():
            continue
        docs = deep_reference_docs(item) if deep_only else item.get("docs", [])
        for doc in docs:
            plan.append({
                "model": name,
                "brand": item["brand"],
                "depth": doc.get("depth"),
                "doc": doc.get("doc"),
                "filename": doc.get("filename") or (doc.get("direct", "").rsplit("/", 1)[-1]),
                "direct": doc.get("direct"),
                "size": doc.get("size"),
                "size_bytes": parse_size(doc.get("size")),
            })
    plan.sort(key=lambda item: (item["brand"], item["model"], item["doc"] or ""))
    return plan


def safe_filename(value: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._()\- ]+", "_", value).strip(" .")
    return cleaned or "manual.pdf"
